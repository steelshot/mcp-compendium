// Command mcpcd serves many MCP servers to AI agents as one compact, searchable endpoint.
package main

import (
	"context"
	"os"
	"os/signal"
	"syscall"

	"github.com/steelshot/mcp-compendium/internal/cli"
)

func main() {
	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	code := cli.Execute(ctx, os.Args[1:], os.Stdin, os.Stdout, os.Stderr)

	stop()
	os.Exit(code)
}
